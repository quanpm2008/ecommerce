package com.example.identity_service;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * Checks the generated OpenAPI document and writes it to {@code openapi.json} (for Postman: Import → File) and
 * {@code api.html} (readable docs) in the module root, so both always match the code. The files are only rewritten
 * when their content changes.
 */
class OpenApiDocsTests extends EndpointTestSupport {

	@Autowired
	private JsonMapper jsonMapper;

	@Test
	void documentsEveryEndpointWithItsSecurityAndWritesTheDocs() throws Exception {
		String body = body(mvc.perform(get("/v3/api-docs")).andExpect(status().isOk()));
		JsonNode spec = jsonMapper.readTree(body);

		assertThat(spec.at("/components/securitySchemes/bearerAuth/scheme").asString()).isEqualTo("bearer");
		assertThat(spec.at("/components/securitySchemes/serviceToken/name").asString()).isEqualTo("X-Service-Token");
		assertThat(spec.at("/paths/~1api~1v1~1identity~1auth~1login/post/security").isEmpty()).isTrue();
		assertThat(spec.at("/paths/~1api~1v1~1identity~1users~1me/get/security/0/bearerAuth").isArray()).isTrue();
		assertThat(spec.at("/paths/~1api~1v1~1identity~1users~1me/get/description").asString())
				.contains("account:read:own");
		assertThat(spec.at("/paths/~1internal~1v1~1identity~1users~1{userId}~1contact/get/security/0/serviceToken")
				.isArray()).isTrue();
		assertThat(spec.at("/paths/~1internal~1v1~1identity~1users~1{userId}~1contact/get/description").asString())
				.contains("notification-service");
		assertThat(spec.at("/paths/~1hello").isMissingNode()).isTrue();

		String pretty = jsonMapper.writerWithDefaultPrettyPrinter().writeValueAsString(spec) + "\n";
		writeIfChanged(Path.of("openapi.json"), pretty);
		writeIfChanged(Path.of("api.html"), html(pretty));
	}

	/** Redoc renders the embedded spec; it needs the CDN script, nothing else (works from file://). */
	private static String html(String spec) {
		return """
				<!DOCTYPE html>
				<html lang="en">
				<head>
				  <meta charset="utf-8">
				  <meta name="viewport" content="width=device-width, initial-scale=1">
				  <title>Identity &amp; Seller API</title>
				  <style>body { margin: 0; }</style>
				</head>
				<body>
				  <!-- Generated by OpenApiDocsTests from /v3/api-docs; do not edit. Live docs: /swagger-ui.html -->
				  <div id="redoc"></div>
				  <script id="spec" type="application/json">
				%s  </script>
				  <script src="https://cdn.redoc.ly/redoc/v2.5.0/bundles/redoc.standalone.js"></script>
				  <script>
				    Redoc.init(JSON.parse(document.getElementById('spec').textContent),
				      { hideDownloadButton: false, expandResponses: '200,201', jsonSampleExpandLevel: 3 },
				      document.getElementById('redoc'));
				  </script>
				</body>
				</html>
				""".formatted(spec.replace("</", "<\\/"));
	}

	private static void writeIfChanged(Path file, String content) throws IOException {
		if (Files.exists(file) && Files.readString(file, StandardCharsets.UTF_8).equals(content)) {
			return;
		}
		Files.writeString(file, content, StandardCharsets.UTF_8);
	}

}
